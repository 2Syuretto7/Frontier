const GD = `import numpy as np

def gd_one_step(X, y, xq, lr):
    w = lr * X.T @ y
    return float(w @ xq)

def linear_attention(Z, WK, WQ, WV):
    q = Z[-1] @ WQ
    return sum((Z[i] @ WV) * float((Z[i] @ WK) @ q) for i in range(len(Z) - 1))

def gd_attention_weights(d, lr):
    WK = np.zeros((d + 1, d))
    WK[:d] = np.eye(d)
    WV = np.zeros((d + 1, d + 1))
    WV[d, d] = lr
    return WK, WK.copy(), WV`;

const BAYES = `import numpy as np

def task_posterior(prior, tasks, examples, eps, m):
    logp = np.log(np.asarray(prior, float))
    for x, y in examples:
        logp += [np.log(1 - eps) if f[x] == y else np.log(eps / (m - 1)) for f in tasks]
    p = np.exp(logp - logp.max())
    return p / p.sum()

def predictive(post, tasks, x, eps, m):
    out = np.full(m, eps / (m - 1))
    for w, f in zip(post, tasks):
        out[f[x]] += w * (1 - eps - eps / (m - 1))
    return out

def evidence_ratio(eps, m):
    return (1 - eps) * (m - 1) / eps`;

