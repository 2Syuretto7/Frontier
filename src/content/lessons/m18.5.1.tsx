const FINITE = `def cond_exp(w, X, cell):
    mass, total = {}, {}
    for o, p in w.items():
        c = cell(o)
        mass[c] = mass.get(c, 0) + p
        total[c] = total.get(c, 0) + p * X(o)
    return {o: total[cell(o)] / mass[cell(o)] for o in w}

def expect_on(w, Z, C):
    return sum(p * Z(o) for o, p in w.items() if o in C)

def satisfies_definition(w, X, Y, cell, tol=1e-12):
    cells = {}
    for o in w:
        cells.setdefault(cell(o), set()).add(o)
    return all(abs(expect_on(w, X, C) - expect_on(w, lambda o: Y[o], C)) < tol for C in cells.values())`;

