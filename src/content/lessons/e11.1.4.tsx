const LEDGER = `from collections import Counter

def usable(doc, purpose, today):
    return (not doc["opt_out"] and purpose in doc["uses"]
            and (doc["expires"] is None or today < doc["expires"]))   # ISO dates compare as strings

def drop_reasons(docs, purpose, today):
    c = Counter()
    for d in docs:                                # the first failing condition is the reason
        if d["opt_out"]:
            c["opt-out"] += 1
        elif purpose not in d["uses"]:
            c["use"] += 1
        elif d["expires"] is not None and today >= d["expires"]:
            c["expired"] += 1
    return c

def allocate(weights, caps, budget):
    alloc, free = {}, set(weights)
    while free:
        lam = (budget - sum(alloc.values())) / sum(weights[s] for s in free)
        capped = {s for s in free if lam * weights[s] >= caps[s]}
        if not capped:                            # everyone left gets the same tokens per unit weight
            alloc.update({s: lam * weights[s] for s in sorted(free)})
            break
        for s in sorted(capped):
            alloc[s] = caps[s]                    # fix sources that would exceed what they have
        free -= capped
    return alloc`;

