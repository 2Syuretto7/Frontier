const ORDER = `import heapq, re

def imports(src):
    names = re.findall(r"^\\s*(?:from\\s+(\\w+)|import\\s+(\\w+))", src, re.M)
    return {a or b for a, b in names}

def dep_order(files):
    mod = {p.rsplit("/", 1)[-1].removesuffix(".py"): p for p in files}
    deps = {p: {mod[m] for m in imports(s) if m in mod and mod[m] != p} for p, s in files.items()}
    users = {p: [q for q in files if p in deps[q]] for p in files}
    indeg = {p: len(deps[p]) for p in files}
    ready = [p for p in files if indeg[p] == 0]
    heapq.heapify(ready)
    order = []
    while ready:
        p = heapq.heappop(ready)                  # smallest path among files whose imports are all placed
        order.append(p)
        for q in users[p]:
            indeg[q] -= 1
            if indeg[q] == 0:
                heapq.heappush(ready, q)
    return order + sorted(p for p in files if p not in order)   # files in an import cycle go last

def pack(files, order):
    return "\\n".join(f"# {p}\\n{files[p]}" for p in order)`;

