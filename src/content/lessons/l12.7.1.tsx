const MASKED = `def mask_tokens(x, u, alpha, M=-1):
    return [xi if ui < alpha else M for xi, ui in zip(x, u)]   # each token survives with probability alpha

def unmask_prob(a_s, a_t):
    return (a_s - a_t) / (1 - a_t)                             # chance a masked token is revealed going from t to s

def masked_loss(logprobs, masked, t):
    return -sum(lp for lp, m in zip(logprobs, masked) if m) / t   # linear schedule: weight 1/t`;

const SAMPLE = `def unmask_schedule(L, K):
    return [L // K + (1 if i < L % K else 0) for i in range(K)]

def top_k_positions(conf, masked, k):
    cand = [i for i in range(len(conf)) if masked[i]]
    return sorted(cand, key=lambda i: -conf[i])[:k]            # reveal the most confident predictions first

def parallel_valid(joint):
    m1, m2 = {}, {}
    for (a, b), p in joint.items():
        m1[a] = m1.get(a, 0) + p
        m2[b] = m2.get(b, 0) + p
    return sum(m1[a] * m2[b] for (a, b) in joint)              # independent draws from the marginals`;

