      <p>
        A policy gradient credits every action in an episode with the episode&apos;s result. For actions that did not
        matter, that credit is a coin toss: sometimes the episode they were in succeeded and sometimes it failed, for reasons
        that had nothing to do with them. On average these credits cancel, but each adds noise, and the noise grows with
        the number of actions while the signal from the few decisive ones does not. Long-horizon reinforcement learning is
        mostly about keeping that noise down: by not training on what the policy did not choose, by crediting actions only
        with what came after them, and by discounting, estimating values or adding intermediate rewards.
      </p>
