const CREDIT = `def reward_to_go(rewards, gamma):
    out, g = [], 0.0
    for r in reversed(rewards):
        g = r + gamma * g                                  # credit only for rewards at or after this step
        out.append(g)
    return out[::-1]

def loss_mask(segments):
    return [1 if role == "model" else 0 for role, n in segments for _ in range(n)]

def token_advantages(turn_adv, segments):
    out, i = [], 0
    for role, n in segments:
        if role == "model":
            out += [turn_adv[i]] * n                       # every token of a turn shares its advantage
            i += 1
        else:
            out += [0.0] * n                               # tool output and user text are not actions
    return out`;

