"use client";

import { useState } from "react";

/** The random variable X(ω) on [0, 1) with Lebesgue measure. */
export const X = (w: number) => 0.45 + 0.3 * Math.sin(3 * Math.PI * w) + 0.35 * w * w;

const M = 2048;
/** E[X | G_k] on the 2^k dyadic cells, and the mean squared residual E(X − E[X | G_k])². */
export function condExp(k: number) {
  const n = 2 ** k, per = M / n;
  const means = Array.from({ length: n }, (_, j) => {
    let s = 0;
    for (let i = 0; i < per; i++) s += X((j * per + i + 0.5) / M);
    return s / per;
  });
  let r = 0;
  for (let i = 0; i < M; i++) r += (X((i + 0.5) / M) - means[Math.floor(i / per)]) ** 2;
  return { means, resid: r / M, mean: means.reduce((a, b) => a + b, 0) / n };
}

export function CellAverageViz() {
  const [k, setK] = useState(2);
  const [prev, setPrev] = useState(false);
  const c = condExp(k), p = k > 0 ? condExp(k - 1) : null;
  const n = c.means.length;
  const W = 330, H = 150, X0 = 26, PW = 296, Y0 = 8, PH = 124, TOP = 1.1;
  const sx = (w: number) => X0 + w * PW, sy = (y: number) => Y0 + PH - (y / TOP) * PH;
  const curve = Array.from({ length: 301 }, (_, i) => i / 300).map((w, i) => `${i ? "L" : "M"}${sx(w).toFixed(1)},${sy(X(w)).toFixed(1)}`).join(" ");
  const steps = (ms: number[]) => ms.map((v, j) => `M${sx(j / ms.length).toFixed(1)},${sy(v).toFixed(1)} L${sx((j + 1) / ms.length).toFixed(1)},${sy(v).toFixed(1)}`).join(" ");
  return (
    <figure className="viz">
      <div className="viz-controls" style={{ marginTop: 0, flexWrap: "wrap", gap: 8 }}>
        <label className="viz-label" style={{ display: "flex", alignItems: "center", gap: 6 }}>
          σ-algebra of level k = {k}
          <input type="range" min={0} max={7} value={k} onChange={(e) => setK(Number(e.target.value))} aria-label="Dyadic level of the sigma-algebra" />
        </label>
        <button type="button" className="btn" aria-pressed={prev} onClick={() => setPrev((v) => !v)} disabled={k === 0}>
          {prev ? "Hide" : "Show"} level k − 1
        </button>
      </div>
      <svg viewBox={`0 0 ${W} ${H}`} style={{ width: "100%", maxWidth: 440, display: "block", margin: "0 auto" }} role="img" aria-label="A random variable and its conditional expectation given a dyadic sigma-algebra">
        <line x1={X0} x2={X0 + PW} y1={sy(0)} y2={sy(0)} stroke="var(--border)" />
        <line x1={X0} x2={X0} y1={Y0} y2={sy(0)} stroke="var(--border)" />
        {Array.from({ length: Math.min(n, 64) + 1 }, (_, j) => <line key={j} x1={sx(j / Math.min(n, 64))} x2={sx(j / Math.min(n, 64))} y1={sy(0)} y2={sy(0) - 4} stroke="var(--border)" />)}
        {[0, 1].map((v) => <text key={v} x={X0 - 4} y={sy(v) + 4} textAnchor="end" className="viz-label">{v}</text>)}
        {[0, 0.5, 1].map((v) => <text key={v} x={sx(v)} y={H - 2} textAnchor={v === 1 ? "end" : "middle"} className="viz-label">{v}</text>)}
        <path d={curve} fill="none" stroke="var(--text)" strokeWidth={1.2} />
        {prev && p && <path d={steps(p.means)} fill="none" stroke="var(--code-function)" strokeWidth={2} strokeDasharray="4 3" />}
        <path d={steps(c.means)} fill="none" stroke="var(--accent)" strokeWidth={2.5} />
      </svg>
      <div className="mono" style={{ fontSize: 12, margin: "6px 0" }} aria-live="polite">
        {n} cells; E[E[X | G]] = {c.mean.toFixed(4)}; E(X − E[X | G])² = {c.resid.toFixed(4)}
      </div>
      <figcaption className="viz-caption">
        X(ω) on [0, 1) (thin curve) and its conditional expectation given the σ-algebra generated by the 2ᵏ dyadic cells
        (thick steps): on each cell, the average of X there. Its mean never changes, the mean squared residual falls as
        the σ-algebra grows, and averaging the level-k steps over pairs of cells gives exactly the level k − 1 steps: the
        tower property.
      </figcaption>
    </figure>
  );
}
